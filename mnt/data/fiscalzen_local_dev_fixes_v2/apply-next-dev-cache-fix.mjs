#!/usr/bin/env node
/**
 * Patch apps/web Next config to disable webpack persistent cache in DEV.
 *
 * This mitigates Windows-only issues like:
 * - ENOENT: .next/cache/webpack/.../*.pack.gz
 * - Cannot find module .next/server/middleware-manifest.json
 * - Random "Invalid or unexpected token" caused by corrupted cached chunks
 *
 * Usage:
 *   node tools/apply-next-dev-cache-fix.mjs
 */

import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const webDir = path.join(root, 'apps', 'web');

const candidates = [
  path.join(webDir, 'next.config.mjs'),
  path.join(webDir, 'next.config.js'),
  path.join(webDir, 'next.config.ts'),
];

function exists(p) {
  try {
    fs.accessSync(p);
    return true;
  } catch {
    return false;
  }
}

function writeFile(p, content) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content, 'utf8');
}

function patchJsOrMjs(filePath) {
  const src = fs.readFileSync(filePath, 'utf8');

  const marker = '/* FISCALZEN_DEV_CACHE_FIX */';
  if (src.includes(marker)) {
    console.log(`[NOOP] ${path.relative(root, filePath)} (already_patched)`);
    return;
  }

  // We try to be conservative: wrap/extend an existing webpack(...) function if present.
  // If not present, we append one.
  let patched = src;

  const hasWebpack = /webpack\s*\(\s*config\s*,\s*\{[^}]*dev[^}]*\}\s*\)\s*\{/.test(src);

  if (hasWebpack) {
    // Inject inside the existing webpack function right after its opening brace.
    patched = patched.replace(
      /(webpack\s*\(\s*config\s*,\s*\{[^}]*dev[^}]*\}\s*\)\s*\{)/,
      `$1\n    ${marker}\n    if (dev) {\n      config.cache = false;\n    }\n`
    );
  } else {
    // Append webpack field to the exported config object.
    // Works for common patterns: module.exports = { ... } OR export default { ... }.
    const isExportDefaultObject = /export\s+default\s+\{/.test(src);
    const isModuleExportsObject = /module\.exports\s*=\s*\{/.test(src);

    if (isExportDefaultObject) {
      patched = patched.replace(
        /export\s+default\s*\{/, 
        `export default {\n  webpack(config, { dev }) {\n    ${marker}\n    if (dev) {\n      config.cache = false;\n    }\n    return config;\n  },`
      );
    } else if (isModuleExportsObject) {
      patched = patched.replace(
        /module\.exports\s*=\s*\{/, 
        `module.exports = {\n  webpack(config, { dev }) {\n    ${marker}\n    if (dev) {\n      config.cache = false;\n    }\n    return config;\n  },`
      );
    } else {
      // Fallback: replace entire file with a minimal config, but keep a backup.
      const backup = `${filePath}.bak`;
      fs.writeFileSync(backup, src, 'utf8');
      patched = `/** Auto-generated by apply-next-dev-cache-fix.mjs */\n/** Backup created at: ${path.basename(backup)} */\n\n/** @type {import('next').NextConfig} */\nconst nextConfig = {\n  webpack(config, { dev }) {\n    ${marker}\n    if (dev) {\n      config.cache = false;\n    }\n    return config;\n  },\n};\n\nexport default nextConfig;\n`;
      console.log(`[WARN] Unrecognized next config format. Backed up to ${path.relative(root, backup)} and replaced with a minimal config.`);
    }
  }

  fs.writeFileSync(filePath, patched, 'utf8');
  console.log(`[OK] ${path.relative(root, filePath)} (dev_webpack_cache_disabled)`);
}

function patchTs(filePath) {
  const src = fs.readFileSync(filePath, 'utf8');
  const marker = '/* FISCALZEN_DEV_CACHE_FIX */';
  if (src.includes(marker)) {
    console.log(`[NOOP] ${path.relative(root, filePath)} (already_patched)`);
    return;
  }

  // TS config usually: const nextConfig: NextConfig = { ... }; export default nextConfig;
  let patched = src;
  const hasWebpack = /webpack\s*\(\s*config\s*,\s*\{[^}]*dev[^}]*\}\s*\)\s*\{/.test(src);
  if (hasWebpack) {
    patched = patched.replace(
      /(webpack\s*\(\s*config\s*,\s*\{[^}]*dev[^}]*\}\s*\)\s*\{)/,
      `$1\n    ${marker}\n    if (dev) {\n      (config as any).cache = false;\n    }\n`
    );
  } else {
    // Insert into first object literal assignment to nextConfig.
    patched = patched.replace(
      /(=\s*\{)/,
      `$1\n  webpack(config, { dev }) {\n    ${marker}\n    if (dev) {\n      (config as any).cache = false;\n    }\n    return config;\n  },`
    );
  }

  fs.writeFileSync(filePath, patched, 'utf8');
  console.log(`[OK] ${path.relative(root, filePath)} (dev_webpack_cache_disabled)`);
}

const configFile = candidates.find(exists);
if (!configFile) {
  // Create a next.config.mjs
  const target = path.join(webDir, 'next.config.mjs');
  const content = `/** Auto-generated by apply-next-dev-cache-fix.mjs */\n\n/** @type {import('next').NextConfig} */\nconst nextConfig = {\n  webpack(config, { dev }) {\n    /* FISCALZEN_DEV_CACHE_FIX */\n    if (dev) {\n      config.cache = false;\n    }\n    return config;\n  },\n};\n\nexport default nextConfig;\n`;
  writeFile(target, content);
  console.log(`[OK] ${path.relative(root, target)} (created_dev_cache_fix_config)`);
} else if (configFile.endsWith('.ts')) {
  patchTs(configFile);
} else {
  patchJsOrMjs(configFile);
}

console.log('\nNext steps:');
console.log('1) node tools/clean-web-next-cache.mjs');
console.log('2) pnpm --filter @fiscalzen/web dev');
